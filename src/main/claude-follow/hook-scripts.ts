import { posix, win32 } from "node:path";
import { CLAUDE_CLI_CREDENTIAL_OVERRIDE_ENV_NAMES } from "../orchestration/claude-cli-profile-environment";

/**
 * The scripts that let a plain `claude`, typed in a terminal outside Codara,
 * follow the account active in Codara (claude-follow.ts has the whole
 * picture). Pure text: nothing here touches a file.
 *
 * Each script defines one `claude` function in an interactive shell. On every
 * call the function decides with shell builtins only, so no process starts
 * before Claude Code does:
 *
 *  - Codara is still installed: the app path Codara recorded at its last
 *    start exists;
 *  - a Codara-managed account is active: the flag file Codara keeps exists;
 *  - the shell is not one of Codara's own panes, which set things up
 *    themselves;
 *  - the user chose nothing of their own: no CLAUDE_CONFIG_DIR and none of
 *    the variables that route Claude Code to another login.
 *
 * Only then does the real `claude` run with CLAUDE_CONFIG_DIR at Codara's
 * live slot, for that child alone; otherwise it runs untouched. The function
 * is not defined at all when the user already has a `claude` alias or
 * function, when the shell is a Codara pane (whose own `claude` wrapper must
 * keep its name), or when the app is gone. The line in the user's startup
 * file sources the script only while it exists, so deleting Codara's folder
 * or the app makes everything inert.
 */

export const CLAUDE_FOLLOW_BLOCK_BEGIN = "# >>> codara studio claude >>>";
export const CLAUDE_FOLLOW_BLOCK_END = "# <<< codara studio claude <<<";
/** First line of the fish drop-in, which Codara owns whole. */
export const CLAUDE_FOLLOW_FISH_HEADER = "# codara studio claude (generated by Codara Studio)";

export type ClaudeFollowShell = "zsh" | "bash" | "fish" | "powershell";

export const CLAUDE_FOLLOW_SCRIPT_NAMES: Readonly<Record<ClaudeFollowShell, string>> = {
  zsh: "claude-follow.zsh",
  bash: "claude-follow.bash",
  fish: "claude-follow.fish",
  powershell: "claude-follow.ps1",
};

/** Variables that mark a shell as one of Codara's own panes (pty-manager.ts). */
export const CODARA_PANE_ENV_NAMES = ["SPARK_AGENT_PANE_ID", "SPARK_AGENT_ARGS_DIR"] as const;

/**
 * A user who set any of these chose a login or provider of their own, and a
 * Codara pane strips them for a managed account; outside, `claude` is then
 * left alone. CLAUDE_CONFIG_DIR leads: a user's own home always wins.
 */
export const CLAUDE_FOLLOW_USER_ENV_NAMES: readonly string[] = [
  "CLAUDE_CONFIG_DIR",
  ...[...CLAUDE_CLI_CREDENTIAL_OVERRIDE_ENV_NAMES].sort(),
];

export interface ClaudeFollowHookInput {
  platform: NodeJS.Platform;
  /** The installed app: the .app bundle, the AppImage file or the installed exe. */
  appPath: string;
  /** Exists while a Codara-managed Claude account is active. */
  flagFile: string;
  /** The live slot, spelled exactly as Codara's own panes pass it. */
  liveConfigDir: string;
}

function assertSafeText(value: string, what: string): void {
  // A newline or NUL in a path would end the quoted word; no real install
  // path has one, so such a value is refused rather than escaped.
  if (!value || /[\u0000\n\r]/.test(value)) {
    throw new TypeError(`${what} cannot be written into a shell script`);
  }
}

/** A POSIX single-quoted word. */
export function shSingleQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

/** A fish single-quoted word: only backslash and quote are special. */
export function fishSingleQuote(value: string): string {
  return `'${value.replace(/[\\']/g, (char) => `\\${char}`)}'`;
}

/** A PowerShell single-quoted (verbatim) string. */
export function psSingleQuote(value: string): string {
  return `'${value.replace(/['\u2018\u2019\u201a\u201b]/g, (char) => `${char}${char}`)}'`;
}

/**
 * A Windows path as Git Bash (MSYS2) spells it: C:\Users\x becomes
 * /c/Users/x and \\server\share becomes //server/share. Used for the tests
 * the hook runs; the value handed to Claude Code keeps the Windows spelling.
 */
export function msysPath(windowsPath: string): string {
  const normalized = windowsPath.replace(/\\/g, "/");
  const drive = /^([A-Za-z]):(\/.*)?$/.exec(normalized);
  if (drive) return `/${drive[1].toLowerCase()}${drive[2] ?? "/"}`;
  return normalized;
}

function zshScript(input: ClaudeFollowHookInput): string {
  const app = shSingleQuote(input.appPath);
  const flag = shSingleQuote(input.flagFile);
  const live = shSingleQuote(input.liveConfigDir);
  const own = CLAUDE_FOLLOW_USER_ENV_NAMES.map((name) => `\${${name}-}`).join("");
  const pane = CODARA_PANE_ENV_NAMES.map((name) => `\${${name}-}`).join("");
  return [
    "# Codara Studio: a plain `claude` follows the account active in Codara.",
    "# Generated at every Codara start and removed with Settings > Accounts.",
    "# Builtins only: nothing starts before Claude Code itself.",
    "() {",
    "  emulate -L zsh",
    `  [[ -z "${pane}" ]] || return 0`,
    `  [[ -e ${app} ]] || return 0`,
    "  (( ! ${+aliases[claude]} )) || return 0",
    "  if (( ${+functions[claude]} )) && [[ \"${__codara_claude_follow-}\" != 1 ]]; then",
    "    return 0",
    "  fi",
    "  typeset -g __codara_claude_follow=1",
    "  function claude {",
    "    emulate -L zsh",
    `    if [[ -z "${own}${pane}" && -f ${flag} && -e ${app} && -d ${live} ]]; then`,
    `      CLAUDE_CONFIG_DIR=${live} command claude "$@"`,
    "    else",
    '      command claude "$@"',
    "    fi",
    "  }",
    "}",
    "",
  ].join("\n");
}

function bashScript(input: ClaudeFollowHookInput): string {
  const windows = input.platform === "win32";
  // Git Bash tests MSYS paths; Claude Code, a Windows program, gets the
  // Windows spelling Codara's own panes use.
  const test = (value: string) => shSingleQuote(windows ? msysPath(value) : value);
  const app = test(input.appPath);
  const flag = test(input.flagFile);
  const liveTest = test(input.liveConfigDir);
  const live = shSingleQuote(input.liveConfigDir);
  const own = CLAUDE_FOLLOW_USER_ENV_NAMES.map((name) => `\${${name}-}`).join("");
  const pane = CODARA_PANE_ENV_NAMES.map((name) => `\${${name}-}`).join("");
  return [
    "# Codara Studio: a plain `claude` follows the account active in Codara.",
    "# Generated at every Codara start and removed with Settings > Accounts.",
    "# Builtins only, bash 3.2 compatible: nothing starts before Claude Code.",
    `if [ -z "${pane}" ] && [ -e ${app} ] \\`,
    "  && ! alias claude >/dev/null 2>&1 \\",
    '  && { [ "${__codara_claude_follow-}" = 1 ] || ! declare -F claude >/dev/null 2>&1; }; then',
    "  __codara_claude_follow=1",
    "  function claude {",
    `    if [ -z "${own}${pane}" ] && [ -f ${flag} ] && [ -e ${app} ] && [ -d ${liveTest} ]; then`,
    `      CLAUDE_CONFIG_DIR=${live} command claude \${1+"$@"}`,
    "    else",
    '      command claude ${1+"$@"}',
    "    fi",
    "  }",
    "fi",
    "",
  ].join("\n");
}

function fishScript(input: ClaudeFollowHookInput): string {
  const app = fishSingleQuote(input.appPath);
  const flag = fishSingleQuote(input.flagFile);
  const live = fishSingleQuote(input.liveConfigDir);
  const own = CLAUDE_FOLLOW_USER_ENV_NAMES.map((name) => `$${name}`).join("");
  const pane = CODARA_PANE_ENV_NAMES.map((name) => `$${name}`).join("");
  // `set -lx` inside the if block scopes the variable to that block, so
  // only the child sees it; older fish lacks the `VAR=value cmd` form.
  return [
    "# Codara Studio: a plain `claude` follows the account active in Codara.",
    "# Generated at every Codara start and removed with Settings > Accounts.",
    `if status is-interactive; and test -z "${pane}"; and test -e ${app}`,
    "    if not functions -q claude; or set -q __codara_claude_follow",
    "        set -g __codara_claude_follow 1",
    "        function claude",
    `            if test -z "${own}${pane}"; and test -f ${flag}; and test -e ${app}; and test -d ${live}`,
    `                set -lx CLAUDE_CONFIG_DIR ${live}`,
    "                command claude $argv",
    "            else",
    "                command claude $argv",
    "            end",
    "        end",
    "    end",
    "end",
    "",
  ].join("\n");
}

function powershellScript(input: ClaudeFollowHookInput): string {
  const app = psSingleQuote(input.appPath);
  const flag = psSingleQuote(input.flagFile);
  const live = psSingleQuote(input.liveConfigDir);
  const own = CLAUDE_FOLLOW_USER_ENV_NAMES.map((name) => `$env:${name}`).join(" -or ");
  const pane = CODARA_PANE_ENV_NAMES.map((name) => `$env:${name}`).join(" -or ");
  return [
    "# Codara Studio: a plain `claude` follows the account active in Codara.",
    "# Generated at every Codara start and removed with Settings > Accounts.",
    `if (-not (${pane}) -and (Test-Path -LiteralPath ${app}) -and`,
    "    -not (Get-Alias -Name claude -ErrorAction SilentlyContinue) -and",
    "    ($global:__CodaraClaudeFollow -or -not (Get-Command -Name claude -CommandType Function -ErrorAction SilentlyContinue))) {",
    "    $global:__CodaraClaudeFollow = $true",
    "    function global:claude {",
    "        $target = Get-Command -Name claude -CommandType Application, ExternalScript -ErrorAction SilentlyContinue | Select-Object -First 1",
    "        if (-not $target) {",
    "            Write-Error -Category ObjectNotFound -Message \"The term 'claude' is not recognized as a name of a cmdlet, function, script file, or executable program.\"",
    "            return",
    "        }",
    `        $follow = -not (${own} -or ${pane}) -and`,
    `            [System.IO.File]::Exists(${flag}) -and (Test-Path -LiteralPath ${app}) -and`,
    `            [System.IO.Directory]::Exists(${live})`,
    "        if (-not $follow) {",
    "            if ($MyInvocation.ExpectingInput) { $input | & $target @args } else { & $target @args }",
    "            return",
    "        }",
    `        $env:CLAUDE_CONFIG_DIR = ${live}`,
    "        try {",
    "            if ($MyInvocation.ExpectingInput) { $input | & $target @args } else { & $target @args }",
    "        } finally {",
    "            Remove-Item -Path Env:CLAUDE_CONFIG_DIR -ErrorAction SilentlyContinue",
    "        }",
    "    }",
    "}",
    "",
  ].join("\r\n");
}

/** The script Codara keeps in its own folder for one shell. */
export function renderClaudeFollowScript(shell: ClaudeFollowShell, input: ClaudeFollowHookInput): string {
  assertSafeText(input.appPath, "The app path");
  assertSafeText(input.flagFile, "The flag file");
  assertSafeText(input.liveConfigDir, "The live slot");
  switch (shell) {
    case "zsh":
      return zshScript(input);
    case "bash":
      return bashScript(input);
    case "fish":
      return fishScript(input);
    case "powershell":
      return powershellScript(input);
  }
}

// ---------------------------------------------------------------------------
// The line in the user's startup file.

export interface ClaudeFollowLineInput {
  platform: NodeJS.Platform;
  /** The user's home directory, as the shell's $HOME names it. */
  homeDir: string;
  /** The script in Codara's folder the line sources. */
  scriptPath: string;
}

/** Inside POSIX double quotes only these four characters are special. */
function shDoubleQuoteBody(value: string): string {
  return value.replace(/[\\"$`]/g, (char) => `\\${char}`);
}

function relativeUnder(path: string, home: string, windows: boolean): string | null {
  const api = windows ? win32 : posix;
  const relative = api.relative(api.resolve(home), api.resolve(path));
  if (!relative || relative.startsWith("..") || api.isAbsolute(relative)) return null;
  return relative;
}

/**
 * The script path as a POSIX shell word: "$HOME/..." when it sits under the
 * home directory, so a dotfile synced to another computer still names the
 * right place there, and a single-quoted absolute path otherwise.
 */
function posixScriptWord(input: ClaudeFollowLineInput): string {
  const windows = input.platform === "win32";
  const relative = relativeUnder(input.scriptPath, input.homeDir, windows);
  if (relative !== null) {
    const forward = windows ? relative.replace(/\\/g, "/") : relative;
    return `"$HOME/${shDoubleQuoteBody(forward)}"`;
  }
  return shSingleQuote(windows ? msysPath(input.scriptPath) : input.scriptPath);
}

/**
 * A PowerShell double-quoted string that is pure ASCII, so the line reads
 * the same whatever encoding the user's profile is in (Windows PowerShell
 * reads a profile without a BOM in the ANSI code page).
 */
function psAsciiDoubleQuoted(value: string): string {
  let out = "";
  for (const char of value) {
    const code = char.codePointAt(0)!;
    if (char === "`" || char === "$" || char === '"') out += `\`${char}`;
    else if (code >= 0x20 && code < 0x7f) out += char;
    else if (code <= 0xffff) out += `$([char]0x${code.toString(16).padStart(4, "0")})`;
    else out += `$([char]::ConvertFromUtf32(0x${code.toString(16)}))`;
  }
  return out;
}

/**
 * $env:USERPROFILE rather than $HOME: PowerShell builds $HOME from
 * HOMEDRIVE and HOMEPATH, which a domain policy can point at a network
 * share, while Codara's folder sits in the profile folder (os.homedir()).
 */
function powershellScriptWord(input: ClaudeFollowLineInput): string {
  const relative = relativeUnder(input.scriptPath, input.homeDir, input.platform === "win32");
  if (relative !== null) return `"$env:USERPROFILE\\${psAsciiDoubleQuoted(relative)}"`;
  return `"${psAsciiDoubleQuoted(input.scriptPath)}"`;
}

/**
 * The one guarded line, between Codara's markers, that a startup file gets.
 * It sources the script only while the script exists and never fails: a
 * missing folder, a deleted app or a blocked script leaves the shell as it
 * would be without Codara. bash lines also check BASH_VERSION because
 * ~/.profile is read by every POSIX login shell.
 */
export function renderClaudeFollowBlock(
  shell: Exclude<ClaudeFollowShell, "fish">,
  input: ClaudeFollowLineInput,
): string[] {
  assertSafeText(input.scriptPath, "The script path");
  let line: string;
  if (shell === "powershell") {
    const word = powershellScriptWord(input);
    line = `if (Test-Path -LiteralPath ${word}) { try { . ${word} } catch { } }`;
  } else {
    const word = posixScriptWord(input);
    const guard = shell === "bash" ? `[ -n "\${BASH_VERSION-}" ] && [ -f ${word} ]` : `[ -f ${word} ]`;
    line = `if ${guard}; then . ${word}; fi`;
  }
  return [CLAUDE_FOLLOW_BLOCK_BEGIN, line, CLAUDE_FOLLOW_BLOCK_END];
}

/** The fish drop-in in conf.d: Codara owns the whole file. */
export function renderClaudeFollowFishDropIn(input: ClaudeFollowLineInput): string {
  assertSafeText(input.scriptPath, "The script path");
  const relative = relativeUnder(input.scriptPath, input.homeDir, false);
  const word =
    relative !== null ? `"$HOME/${relative.replace(/[\\"$]/g, (char) => `\\${char}`)}"` : fishSingleQuote(input.scriptPath);
  return [
    CLAUDE_FOLLOW_FISH_HEADER,
    "# A plain `claude` follows the account active in Codara Studio; removed with",
    "# Settings > Accounts, and does nothing once Codara Studio is gone.",
    `test -f ${word}; and source ${word}`,
    "",
  ].join("\n");
}
