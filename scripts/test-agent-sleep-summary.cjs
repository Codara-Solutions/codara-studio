// The line a sleeping agent pane's card shows (src/main/agent-sleep-summary.ts):
// what the session's transcript, the agent's rail note, the notifier's last
// prompt and the tab title say, in that order, read with the session index's
// own line parsers.
//
//   node scripts/test-agent-sleep-summary.cjs
//
// esbuild-bundles the REAL module and reads transcripts written to a temp
// folder; nothing outside it is touched.

const path = require("node:path");
const os = require("node:os");
const fs = require("node:fs");
const esbuild = require("esbuild");

const ROOT = path.resolve(__dirname, "..");
const SHARED_DIR = path.join(ROOT, "src", "shared");

const sharedAlias = {
  name: "shared-alias",
  setup(build) {
    build.onResolve({ filter: /^@shared\// }, (args) => ({
      path: path.join(SHARED_DIR, `${args.path.slice("@shared/".length)}.ts`),
    }));
  },
};

const line = (record) => `${JSON.stringify(record)}\n`;
const user = (text, extra = {}) =>
  line({ type: "user", timestamp: "2026-10-27T10:00:00.000Z", message: { role: "user", content: text }, ...extra });
const assistant = (text) =>
  line({ type: "assistant", timestamp: "2026-10-27T10:01:00.000Z", message: { role: "assistant", content: [{ type: "text", text }] } });
const aiTitle = (title) => line({ type: "ai-title", aiTitle: title, sessionId: "s" });
const customTitle = (title) => line({ type: "custom-title", customTitle: title, sessionId: "s" });

async function main() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "codara-sleep-summary-"));
  process.on("exit", () => fs.rmSync(dir, { recursive: true, force: true }));
  const outfile = path.join(dir, "summary.cjs");
  await esbuild.build({
    entryPoints: [path.join(ROOT, "src", "main", "agent-sleep-summary.ts")],
    bundle: true,
    platform: "node",
    format: "cjs",
    outfile,
    plugins: [sharedAlias],
    logLevel: "silent",
  });
  const { readTranscriptFacts, describeSleepingAgent } = require(outfile);

  let failures = 0;
  const check = (name, cond, detail) => {
    if (!cond) failures += 1;
    console.log(`${cond ? "PASS" : "FAIL"} ${name}${!cond && detail !== undefined ? `: ${JSON.stringify(detail)}` : ""}`);
  };
  let n = 0;
  const transcript = (text, name = `s${(n += 1)}.jsonl`) => {
    const file = path.join(dir, name);
    fs.writeFileSync(file, text);
    return file;
  };
  const describe = (extra) =>
    describeSleepingAgent({ runtime: "claude", transcriptPath: null, notifierPrompt: null, agentNote: null, tabTitle: null, ...extra });

  // ── Claude transcripts ──
  let file = transcript(user("Fix the zebra parser") + assistant("On it.") + aiTitle("Zebra parser fix") + user("add a test too") + aiTitle("Zebra parser fix and tests"));
  let facts = await readTranscriptFacts(file, "claude");
  check(
    "the newest ai-title, the first and the last prompt are read",
    facts.aiTitle === "Zebra parser fix and tests" && facts.firstPrompt === "Fix the zebra parser" && facts.lastPrompt === "add a test too",
    facts,
  );
  let summary = await describe({ transcriptPath: file });
  check(
    "the card shows the session's title and the last thing asked",
    summary.title === "Zebra parser fix and tests" && summary.detail === "add a test too" && summary.source === "ai-title",
    summary,
  );

  file = transcript(aiTitle("Zebra parser fix") + user("hello") + customTitle("my zebra work"));
  summary = await describe({ transcriptPath: file });
  check("the user's /rename wins over the agent's title, even appended last", summary.title === "my zebra work" && summary.source === "custom-title", summary);

  file = transcript(
    user("<command-name>/clear</command-name>") +
      user("Caveat: The messages below were generated by the user while running local commands.", { isMeta: true }) +
      user("side thread", { isSidechain: true }) +
      user("Refactor the billing module"),
  );
  summary = await describe({ transcriptPath: file });
  check("without a title, the prompt skips meta, sidechain and injected records", summary.title === "Refactor the billing module", summary);

  file = transcript(user("first\nline   two") + '{"type":"user","message":{"role":"user","content":"cut');
  facts = await readTranscriptFacts(file, "claude");
  check("a cut last line (still being written) is ignored without throwing", facts.firstPrompt === "first line two" && /^first\s+line two$/.test(facts.lastPrompt ?? ""), facts);

  file = transcript(`﻿${user("with a BOM").replace(/\n$/, "\r\n")}${aiTitle("Windows line ends").replace(/\n$/, "\r\n")}`);
  facts = await readTranscriptFacts(file, "claude");
  check("CRLF lines parse", facts.aiTitle === "Windows line ends", facts);

  const filler = line({ type: "assistant", message: { role: "assistant", content: [{ type: "tool_use", name: "Read", input: { x: "y".repeat(2000) } }] } });
  let big = user("the very first ask");
  while (big.length < 300_000) big += filler;
  big += aiTitle("Title deep in the file");
  while (big.length < 600_000) big += filler;
  file = transcript(big + user("the last ask"));
  facts = await readTranscriptFacts(file, "claude", { fullReadMaxBytes: 100_000, headBytes: 50_000, tailBytes: 100_000 });
  check(
    "a transcript over the read limit gives its head and tail: the first and last prompts, not the middle",
    facts.firstPrompt === "the very first ask" && facts.lastPrompt === "the last ask" && facts.aiTitle === null,
    facts,
  );
  facts = await readTranscriptFacts(file, "claude");
  check("within the limit the whole file is read", facts.aiTitle === "Title deep in the file", facts);

  check("a missing transcript is null", (await readTranscriptFacts(path.join(dir, "nope.jsonl"), "claude")) === null);
  check("a path that is not a transcript is null", (await readTranscriptFacts(path.join(dir, "summary.cjs"), "claude")) === null);
  facts = await readTranscriptFacts(transcript(""), "claude");
  check("an empty transcript has no facts", facts && facts.aiTitle === null && facts.firstPrompt === null, facts);

  // ── Other CLIs ──
  file = transcript(
    line({ type: "session_meta", payload: { id: "c1", cwd: "/p", source: "cli", originator: "codex_cli_rs" } }) +
      line({ type: "response_item", payload: { type: "message", role: "user", content: [{ type: "input_text", text: "<environment_context>\n<cwd>/p</cwd>\n</environment_context>" }] } }) +
      line({ type: "response_item", payload: { type: "message", role: "user", content: [{ type: "input_text", text: "Speed up the CI" }] } }),
  );
  summary = await describeSleepingAgent({ runtime: "codex", transcriptPath: file, notifierPrompt: null, agentNote: null, tabTitle: null });
  check("codex: the first real prompt, not the environment block", summary?.title === "Speed up the CI", summary);

  file = transcript(
    line({ type: "session", id: "p1", cwd: "/p" }) +
      line({ type: "message", message: { role: "user", content: [{ type: "text", text: "Write the release notes" }] } }),
  );
  summary = await describeSleepingAgent({ runtime: "pi", transcriptPath: file, notifierPrompt: null, agentNote: null, tabTitle: null });
  check("pi: its first prompt", summary?.title === "Write the release notes", summary);

  const grokDir = path.join(dir, "grok-session");
  fs.mkdirSync(grokDir);
  fs.writeFileSync(path.join(grokDir, "summary.json"), JSON.stringify({ generated_title: "Grok's own title" }));
  file = path.join(grokDir, "chat_history.jsonl");
  fs.writeFileSync(file, line({ type: "user", content: [{ type: "text", text: "hi grok" }] }));
  summary = await describeSleepingAgent({ runtime: "grok", transcriptPath: file, notifierPrompt: null, agentNote: null, tabTitle: null });
  check("grok: the title beside its history", summary?.title === "Grok's own title", summary);

  // ── Without a transcript ──
  summary = await describe({ agentNote: "Migrating the auth tests", notifierPrompt: "keep going" });
  check("the agent's own rail note, with the last prompt as detail", summary.title === "Migrating the auth tests" && summary.detail === "keep going" && summary.source === "agent-note", summary);
  summary = await describe({ notifierPrompt: "  why is the build\nred?  " });
  check("the notifier's last prompt, on one line, without a detail repeating it", summary.title === "why is the build red?" && summary.detail === null && summary.source === "prompt", summary);
  summary = await describe({ tabTitle: "api refactor" });
  check("a telling tab title", summary.title === "api refactor" && summary.source === "tab-title", summary);
  check("a generic tab title says nothing", (await describe({ tabTitle: "terminals" })) === null && (await describe({ tabTitle: "Claude Code" })) === null);
  check("nothing at all is null", (await describe({})) === null);
  summary = await describe({ notifierPrompt: `\x1b[31m${"long ".repeat(80)}\x1b[0m` });
  check("colors are stripped and a long line is cut", !summary.title.includes("\x1b") && summary.title.length <= 120 && summary.title.endsWith("…"), summary);
  summary = await describeSleepingAgent(
    { runtime: "claude", transcriptPath: "/x.jsonl", notifierPrompt: "fallback", agentNote: null, tabTitle: null },
    { readFacts: async () => { throw new Error("EACCES"); } },
  );
  check("an unreadable transcript falls back", summary?.title === "fallback", summary);

  if (failures > 0) {
    console.error(`\n${failures} check(s) failed`);
    process.exit(1);
  }
  console.log("\nall agent sleep summary checks passed");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
